function detectObsidianLanguage(): Language {
  let value = "";
  try {
    value = globalThis.window?.localStorage?.getItem("language") ?? "";
  } catch {
    // Storage can be unavailable in restricted test or startup contexts.
  }
  if (!value) {
    try {
      value = globalThis.document?.documentElement?.lang ?? "";
    } catch {
      // Fall through to the browser locale.
    }
  }
  if (!value) value = globalThis.navigator?.language ?? "";
  return value.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function resolveLanguage(preference: LanguagePreference | undefined): Language {
  return preference === "zh" || preference === "en" ? preference : detectObsidianLanguage();
}

export function translate(language: Language, source: string, variables?: Variables): string {
  const template = language === "zh" ? ZH[source] ?? source : source;
  if (!variables) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.hasOwn(variables, key) ? String(variables[key]) : match);
}

/** A provider level name as shown to the user; unknown levels stay as the provider wrote them. */
export function thinkingLevelName(language: Language, level: string): string {
  return language === "zh" ? ZH_THINKING_LEVELS[level] ?? level : level;
}
